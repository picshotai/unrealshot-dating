-- ==============================================================================
-- Restore the automated signup follow-up emails (/api/send-followup-emails).
--
-- The dating-pivot master migration never recreated followup_email_logs, so the
-- route's log insert failed. The eligibility function also excluded anyone with
-- a credits row, but the app creates a 0-credit row on first dashboard visit,
-- so almost nobody qualified. Safe to run more than once.
-- ==============================================================================

create table if not exists public.followup_email_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  email_type text not null, -- '30min' or '4hour'
  sent_at timestamptz not null default now(),
  unique (user_id, email_type) -- never send the same stage twice
);

alter table public.followup_email_logs enable row level security;
-- No policies: only the service role (which bypasses RLS) reads or writes it.

create or replace function public.get_eligible_users_for_followup(
  start_offset interval,
  end_offset interval,
  target_email_type text
)
returns table (id uuid, email varchar)
language sql
stable
security definer
set search_path = public
as $$
  select au.id, au.email::varchar
  from auth.users au
  where au.email is not null
    -- signed up inside the target window
    and au.created_at < (now() - start_offset)
    and au.created_at > (now() - end_offset)
    -- hasn't had this stage yet
    and not exists (
      select 1 from public.followup_email_logs fel
      where fel.user_id = au.id and fel.email_type = target_email_type
    )
    -- has no spendable credits (a 0-credit row is created on first visit)
    and not exists (
      select 1 from public.credits c
      where c.user_id = au.id and c.credits > 0
    )
    -- has never paid
    and not exists (
      select 1 from public.dodo_payments dp
      where dp.user_id = au.id and dp.status = 'completed'
    )
    -- hasn't started a shoot
    and not exists (
      select 1 from public.user_shoot_orders o
      where o.user_id = au.id
    )
$$;

revoke all on function public.get_eligible_users_for_followup(interval, interval, text) from public, anon, authenticated;
grant execute on function public.get_eligible_users_for_followup(interval, interval, text) to service_role;
